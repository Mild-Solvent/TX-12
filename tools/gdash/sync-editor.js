// Copies the game's current files into the level editor, so its "Open bundled level" list
// and its Radio tab (which runs the real game code) match what goes on the card.
//   node sync-editor.js           update editors/radio/gdash-files.js and the editor's BUNDLED levels
//   node sync-editor.js --check   exit 1 if either is out of date (run before merging)
const fs = require("fs"), path = require("path");
const root = path.join(__dirname, "../..");
const games = path.join(root, "My_TX-12/SCRIPTS/GAMES");
const editor = path.join(root, "editors/geodash-editor.html");
const filesJs = path.join(root, "editors/radio/gdash-files.js");
const check = process.argv.includes("--check");

const code = {};
for (const f of ["Game-GeometryDash.lua", "GDASH/phys.lua", "GDASH/draw.lua", "GDASH/music.lua", "GDASH/pick.lua"])
  code["/SCRIPTS/GAMES/" + f] = fs.readFileSync(path.join(games, f), "latin1");
const wantFiles = "// Generated by tools/gdash/sync-editor.js from My_TX-12/SCRIPTS/GAMES. Do not edit.\n" +
  "window.GDASH_FILES = " + JSON.stringify(code, null, 0) + ";\n";

const levels = {};
for (const f of fs.readdirSync(path.join(games, "GDASH"))) {
  const m = /^L(\d+)\.lua$/.exec(f);
  if (m) levels[m[1]] = fs.readFileSync(path.join(games, "GDASH", f), "latin1");
}
const html = fs.readFileSync(editor, "utf8");
const wantHtml = html.replace(/\/\*BUNDLED\*\/[\s\S]*?\/\*END\*\//, () => "/*BUNDLED*/" + JSON.stringify(levels) + "/*END*/");

const haveFiles = fs.existsSync(filesJs) ? fs.readFileSync(filesJs, "latin1") : "";
const stale = [];
if (haveFiles !== wantFiles) stale.push("editors/radio/gdash-files.js");
if (html !== wantHtml) stale.push("editors/geodash-editor.html (bundled levels)");
if (check) {
  if (stale.length) { console.log("out of date: " + stale.join(", ") + "\nrun: node tools/gdash/sync-editor.js"); process.exit(1); }
  console.log("editor in sync with My_TX-12 (" + Object.keys(levels).length + " levels)");
} else {
  fs.writeFileSync(filesJs, wantFiles, "latin1");
  fs.writeFileSync(editor, wantHtml, "utf8");
  console.log(stale.length ? "updated: " + stale.join(", ") : "already in sync");
}
